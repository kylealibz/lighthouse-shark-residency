source("R/reproduction.R")
source("R/simulation.R")
source("R/plots.R")
reproduction <- reproduce_residency()
simulation <- simulate_outages()
dir.create("results", showWarnings = FALSE)
write.csv(reproduction$coefficients, "results/table-2-coefficients.csv", row.names = FALSE)
write.csv(reproduction$summary, "results/residency-by-sex.csv", row.names = FALSE)
write.csv(simulation$summary, "results/outage-summary.csv", row.names = FALSE)
write.csv(simulation$replicates, "results/outage-replicates.csv", row.names = FALSE)
writeLines(capture.output(sessionInfo()), "results/session-info.txt")
save_plot("results/residency-by-length.png", function() plot_residency(reproduction))
save_plot("results/outage-effects.png", function() plot_outages(simulation$summary))
save_plot("results/sex-contrast.png", function() plot_outages(simulation$summary, "gap"))
print(reproduction$coefficients, row.names = FALSE)
print(simulation$summary[, c("scenario", "method", "mean_shift_vs_full", "female_minus_male")],
      row.names = FALSE)
